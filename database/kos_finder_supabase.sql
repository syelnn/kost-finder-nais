-- ---------- RESET (aman dijalankan ulang saat development) ----------
DROP VIEW  IF EXISTS v_kos_ringkas CASCADE;
DROP TABLE IF EXISTS review, booking, kamar, kos_fasilitas, fasilitas, foto_kos, kos, "user" CASCADE;
DROP FUNCTION IF EXISTS haversine_km(numeric, numeric, numeric, numeric);
DROP TYPE  IF EXISTS role_enum, status_verifikasi_user_enum, tipe_kos_enum,
                     status_verifikasi_kos_enum, status_kamar_enum, status_booking_enum;

-- ---------- ENUM ----------
CREATE TYPE role_enum                   AS ENUM ('Admin', 'Owner', 'User');
CREATE TYPE status_verifikasi_user_enum AS ENUM ('Menunggu', 'Terverifikasi');
CREATE TYPE tipe_kos_enum               AS ENUM ('Putra', 'Putri', 'Campur');
CREATE TYPE status_verifikasi_kos_enum  AS ENUM ('Menunggu', 'Aktif', 'Nonaktif');
CREATE TYPE status_kamar_enum           AS ENUM ('Kosong', 'Dalam Booking', 'Terisi');
CREATE TYPE status_booking_enum         AS ENUM ('Menunggu', 'Disetujui', 'Ditolak', 'Selesai');

-- ---------- 1. user ----------
-- Catatan: "user" kata kunci di PostgreSQL -> SELALU ditulis dengan tanda kutip ganda.
-- status_verifikasi: Owner baru = 'Menunggu'; Admin & User dibuat langsung 'Terverifikasi' oleh aplikasi.
CREATE TABLE "user" (
    user_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama               varchar(100) NOT NULL,
    email              varchar(100) NOT NULL,
    password           varchar(255) NOT NULL,                       -- hash bcrypt
    role               role_enum NOT NULL DEFAULT 'User',
    no_wa              varchar(20),
    status_verifikasi  status_verifikasi_user_enum NOT NULL DEFAULT 'Menunggu'
);
CREATE UNIQUE INDEX uq_user_email_lower ON "user" (lower(email));

-- ---------- 2. kos ----------
CREATE TABLE kos (
    kos_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id           integer NOT NULL REFERENCES "user"(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    nama_kos           varchar(100) NOT NULL,
    alamat             text NOT NULL,                               -- format: "Jalan, Kecamatan, Kota/Kabupaten" (segmen terakhir = wilayah)
    latitude           numeric(10,7) NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
    longitude          numeric(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    tipe_kos           tipe_kos_enum NOT NULL,
    status_verifikasi  status_verifikasi_kos_enum NOT NULL DEFAULT 'Menunggu'
);
CREATE INDEX idx_kos_owner  ON kos(owner_id);
CREATE INDEX idx_kos_status ON kos(status_verifikasi);
CREATE INDEX idx_kos_koord  ON kos(latitude, longitude);

-- ---------- 3. foto_kos ----------
CREATE TABLE foto_kos (
    foto_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kos_id     integer NOT NULL REFERENCES kos(kos_id) ON UPDATE CASCADE ON DELETE CASCADE,
    path_foto  varchar(255) NOT NULL                                -- path RELATIF, mis. 'kos/melati-1.jpg'
);
CREATE INDEX idx_foto_kos ON foto_kos(kos_id);

-- ---------- 4. fasilitas (master data, dikelola Admin) ----------
CREATE TABLE fasilitas (
    fasilitas_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_fasilitas  varchar(100) NOT NULL
);
CREATE UNIQUE INDEX uq_fasilitas_nama ON fasilitas (lower(nama_fasilitas));

-- ---------- 5. kos_fasilitas (relasi N-N kos <-> fasilitas) ----------
CREATE TABLE kos_fasilitas (
    kos_id        integer NOT NULL REFERENCES kos(kos_id)             ON UPDATE CASCADE ON DELETE CASCADE,
    fasilitas_id  integer NOT NULL REFERENCES fasilitas(fasilitas_id) ON UPDATE CASCADE ON DELETE CASCADE,
    PRIMARY KEY (kos_id, fasilitas_id)
);
CREATE INDEX idx_kos_fasilitas_fas ON kos_fasilitas(fasilitas_id);

-- ---------- 6. kamar ----------
CREATE TABLE kamar (
    kamar_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kos_id        integer NOT NULL REFERENCES kos(kos_id) ON UPDATE CASCADE ON DELETE CASCADE,
    no_kamar      varchar(20) NOT NULL,
    tipe_kamar    varchar(50) NOT NULL,
    harga         integer NOT NULL CHECK (harga >= 0),              -- per bulan (Rupiah)
    status_kamar  status_kamar_enum NOT NULL DEFAULT 'Kosong',
    UNIQUE (kos_id, no_kamar)
);
CREATE INDEX idx_kamar_kos    ON kamar(kos_id);
CREATE INDEX idx_kamar_status ON kamar(status_kamar);

-- ---------- 7. booking ----------
CREATE TABLE booking (
    booking_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kos_id          integer NOT NULL REFERENCES kos(kos_id) ON UPDATE CASCADE ON DELETE CASCADE,
    kamar_id        integer REFERENCES kamar(kamar_id) ON UPDATE CASCADE ON DELETE CASCADE,
    user_id         integer NOT NULL REFERENCES "user"(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    tipe_booking    varchar(20) NOT NULL DEFAULT 'sewa' CHECK (tipe_booking IN ('survey', 'sewa')),
    tanggal_survey  date NOT NULL,
    status_booking  status_booking_enum NOT NULL DEFAULT 'Menunggu',
    dibuat_pada     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_booking_kamar_sewa CHECK (tipe_booking = 'survey' OR kamar_id IS NOT NULL)
);
CREATE INDEX idx_booking_kos     ON booking(kos_id);
CREATE INDEX idx_booking_user    ON booking(user_id);
CREATE INDEX idx_booking_kamar   ON booking(kamar_id);
CREATE INDEX idx_booking_tipe    ON booking(tipe_booking);
CREATE INDEX idx_booking_status  ON booking(status_booking);
CREATE INDEX idx_booking_tanggal ON booking(tanggal_survey);
-- Pengaman level database: 1 kamar hanya boleh punya 1 booking SEWA aktif (Menunggu/Disetujui) -> anti double booking.
-- Booking survey tidak mengunci kamar.
CREATE UNIQUE INDEX uq_booking_aktif_per_kamar ON booking(kamar_id)
    WHERE tipe_booking = 'sewa' AND status_booking IN ('Menunggu', 'Disetujui') AND kamar_id IS NOT NULL;

-- ---------- 8. review (relasi 1-1 dengan booking) ----------
CREATE TABLE review (
    review_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id   integer NOT NULL UNIQUE REFERENCES booking(booking_id) ON UPDATE CASCADE ON DELETE CASCADE,
    rating       integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    komentar     text,
    dibuat_pada  timestamptz NOT NULL DEFAULT now()
);

-- ---------- FUNGSI & VIEW BANTU (bukan tabel baru; hanya mempermudah query) ----------
-- Jarak (km) antara dua koordinat (rumus Haversine)
CREATE FUNCTION haversine_km(lat1 numeric, lon1 numeric, lat2 numeric, lon2 numeric)
RETURNS double precision LANGUAGE sql IMMUTABLE AS $$
    SELECT 6371 * 2 * asin(sqrt(
        power(sin(radians((lat2 - lat1)::double precision) / 2), 2) +
        cos(radians(lat1::double precision)) * cos(radians(lat2::double precision)) *
        power(sin(radians((lon2 - lon1)::double precision) / 2), 2)
    ));
$$;

-- Ringkasan kos: harga mulai, jumlah kamar, kamar kosong, rata-rata rating, wilayah (segmen terakhir alamat)
CREATE VIEW v_kos_ringkas WITH (security_invoker = true) AS
SELECT k.kos_id, k.owner_id, k.nama_kos, k.alamat, k.latitude, k.longitude, k.tipe_kos, k.status_verifikasi,
       trim(regexp_replace(k.alamat, '^.*,', ''))  AS wilayah,
       COALESCE(km.jumlah_kamar, 0)                AS jumlah_kamar,
       COALESCE(km.kamar_kosong, 0)                AS kamar_kosong,
       km.harga_mulai,
       rv.rata_rating,
       COALESCE(rv.jumlah_review, 0)               AS jumlah_review
FROM kos k
LEFT JOIN (
    SELECT kos_id, count(*) AS jumlah_kamar,
           count(*) FILTER (WHERE status_kamar = 'Kosong') AS kamar_kosong,
           min(harga) AS harga_mulai
    FROM kamar GROUP BY kos_id
) km ON km.kos_id = k.kos_id
LEFT JOIN (
    SELECT b_k.kos_id, round(avg(r.rating), 1) AS rata_rating, count(*) AS jumlah_review
    FROM review r
    JOIN booking b ON b.booking_id = r.booking_id
    JOIN kamar b_k ON b_k.kamar_id = b.kamar_id
    GROUP BY b_k.kos_id
) rv ON rv.kos_id = k.kos_id;

